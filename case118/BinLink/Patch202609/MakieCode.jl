function plot1seg(ax,s,e,h,c)
    lines!(ax, [s,s], [h-1,h]; color = c)
    lines!(ax, [s,e], [h,h-1]; color = c)
end
function plot_brac(ax, v, h, c)
    i = 1
    while i < length(v)
        plot1seg(ax, v[i], v[i+1], h, c)
        i += 2
    end
end
